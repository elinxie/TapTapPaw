#!/usr/bin/env python3
"""Builds small preview images of the board's own art for the web page's layout builder and writes them into
web-sync/index.html between the PREVIEW-ASSETS markers (the page stays a single file, nothing is fetched).

Sources: sketch/src/wallpaper/*.c (LVGL SJPG, 240x320) and sketch/src/ui/ui_img_*_png.c (LVGL TRUE_COLOR_ALPHA,
RGB565 with LV_COLOR_16_SWAP=1 + 8 bit alpha). Needs Pillow.  Run: python3 scripts/make_preview_assets.py [--check DIR]
"""
import base64, io, os, re, struct, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "sketch", "src")
PAGE = os.path.join(ROOT, "web-sync", "index.html")
BEGIN, END = "// PREVIEW-ASSETS BEGIN", "// PREVIEW-ASSETS END"


def c_bytes(path, name):
    text = open(path).read()
    m = re.search(r"%s\[\]\s*=\s*\{(.*?)\};" % re.escape(name), text, re.S)
    if not m:
        raise SystemExit("array %s not found in %s" % (name, path))
    return bytes(int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", m.group(1)))


def header(path, key):
    return int(re.search(r"\.header\.%s\s*=\s*(\d+)" % key, open(path).read()).group(1))


def sjpg(data):
    # "_SJPG__\0" "V1.00\0" w u16, h u16, splits u16, split height u16, then split sizes u16 each, then the JPEG pieces
    assert data[:6] == b"_SJPG_", "not an SJPG"
    off = 14
    w, h, n, sh = struct.unpack_from("<HHHH", data, off)
    off += 8
    sizes = struct.unpack_from("<%dH" % n, data, off)
    off += 2 * n
    img = Image.new("RGB", (w, h))
    y = 0
    for s in sizes:
        piece = Image.open(io.BytesIO(data[off:off + s])).convert("RGB")
        img.paste(piece, (0, y))
        y += piece.height
        off += s
    return img


def true_color_alpha(data, w, h):
    img = Image.new("RGBA", (w, h))
    px = img.load()
    for i in range(w * h):
        hi, lo, a = data[3 * i], data[3 * i + 1], data[3 * i + 2]  # LV_COLOR_16_SWAP: high byte first
        v = (hi << 8) | lo
        r, g, b = (v >> 11) & 0x1F, (v >> 5) & 0x3F, v & 0x1F
        px[i % w, i // w] = ((r * 527 + 23) >> 6, (g * 259 + 33) >> 6, (b * 527 + 23) >> 6, a)
    return img


def uri(img, fmt, **kw):
    buf = io.BytesIO()
    img.save(buf, fmt, optimize=True, **kw)
    return "data:image/%s;base64,%s" % ("jpeg" if fmt == "JPEG" else "png", base64.b64encode(buf.getvalue()).decode())


def main():
    check = sys.argv[2] if len(sys.argv) > 2 and sys.argv[1] == "--check" else None
    out = {}
    for i, name in enumerate(["sunny", "cloudy", "rainy", "stormy", "snowy", "night"]):
        path = os.path.join(SRC, "wallpaper", name + ".c")
        arr = re.search(r"uint8_t\s+(\w+)\[\]\s*=", open(path).read()).group(1)  # rain_map, storm_map, ... names differ
        img = sjpg(c_bytes(path, arr))
        assert img.size == (240, 320), img.size
        out["wall%d" % i] = uri(img.resize((120, 160), Image.LANCZOS), "JPEG", quality=62)
        if check: img.save(os.path.join(check, name + ".png"))
    for key, fname in [("cat", "main"), ("eyes", "closeeye"), ("sleepy", "sleepy"), ("clock", "a_clock"), ("hh", "shorthand"),
                       ("mh", "longhand"), ("sh", "secondhand"), ("i0", "sun"), ("i1", "cloud"), ("i2", "rain"), ("i3", "storm"),
                       ("i4", "snow"), ("i5", "moon"),
                       ("pawL", "leftmousepaw"), ("pawD", "rightpawdown"), ("pawU", "rightpawup")]:
        path = os.path.join(SRC, "ui", "ui_img_%s_png.c" % fname)
        img = true_color_alpha(c_bytes(path, "ui_img_%s_png_data" % fname), header(path, "w"), header(path, "h"))
        out[key] = uri(img, "PNG")
        if check: img.save(os.path.join(check, fname + ".png"))
    lines = [BEGIN + " (generated by scripts/make_preview_assets.py from the firmware's own images; do not edit)",
             "const PREVIEW_ART = {"] + ["  %s: '%s'," % (k, v) for k, v in out.items()] + ["};", END]
    page = open(PAGE, "rb").read().decode("utf8")
    if BEGIN in page:
        a, b = page.index(BEGIN), page.index(END) + len(END)
        page = page[:a] + "\n".join(lines) + page[b:]
    else:
        marker = "// ---- UI ---- (everything below needs a browser"
        page = page.replace(marker, "\n".join(lines) + "\n\n" + marker, 1)
    open(PAGE, "wb").write(page.encode("utf8"))
    total = sum(len(v) for v in out.values())
    print("wrote %d images, %d bytes of data URIs; page is now %d bytes" % (len(out), total, len(page.encode("utf8"))))


if __name__ == "__main__":
    main()
